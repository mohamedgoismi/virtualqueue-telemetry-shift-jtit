"""Audit and harmonize EXISTING 4-fold scenario-held-out outputs.
No new model training and no new physical-network data. All computations are
from artifacts already generated by the prior fourfold experimental run.
"""
from pathlib import Path
import numpy as np, pandas as pd, json
from sklearn.metrics import average_precision_score,precision_score,recall_score, brier_score_loss
R=Path(__file__).resolve().parent.parent/'results'
D=pd.read_csv(R/'major_revision_metrics.csv')
P=pd.read_csv(R/'complete_history_oof_predictions.csv')
F=pd.read_csv(R/'new_group_kfold_protocol.csv')
assert F.test_packets.sum()==21600 and F.n_test_scenarios.sum()==72
assert all(F.n_test_scenarios==18)
F.to_csv(R/'verified_fold_sizes.csv',index=False)
# The two distinct estimands that must not be confused.
core=D[(D.train=='complete_frozen')&(D.test=='complete')&(D.model.isin(['LR','HGB']))]
stat=core.groupby('model').average_precision.agg(['mean','std']).reset_index()
pooled=P.groupby('method').apply(lambda d: average_precision_score(d.y,d.p),include_groups=False)
comparison={'macro_fold_AP_LR_minus_HGB':float(stat.set_index('model').loc['LR','mean']-stat.set_index('model').loc['HGB','mean']),
 'pooled_OOF_AP_LR_minus_HGB':float(pooled['LR']-pooled['HGB']),
 'per_model_macro_fold_AP':stat.set_index('model')['mean'].to_dict(),
 'per_model_pooled_OOF_AP':pooled.to_dict()}
(R/'macro_vs_pooled_estimands.json').write_text(json.dumps(comparison,indent=2))
# Alert budget within each of four held-out folds, averages of within-fold ratios.
rows=[]
for (model,fold),part in P.groupby(['method','fold']):
 y=part.y.to_numpy(); p=part.p.to_numpy(); prev=y.mean()
 for b in (.05,.10,.20):
  top=np.argsort(-p,kind='stable')[:int(np.ceil(b*len(p)))]; captured=int(y[top].sum()); cap=float(captured/max(1,y.sum())); ceiling=min(1,b/prev)
  rows.append(dict(model=model,fold=fold,budget=b,AP=average_precision_score(y,p),brier=brier_score_loss(y,p),prevalence=prev,alert_precision=y[top].mean(),capture=cap,ceiling=ceiling,normalized_capture=cap/ceiling,number_alerts=len(top)))
B=pd.DataFrame(rows);B.to_csv(R/'operational_budgets_fourfold.csv',index=False)
# explicit per-fold matched / frozen / equal-size mixed / unseen for honest cross-learner comparison
matched=D[(D.train.isin(['matched','complete_frozen','mixed_equal_packet_count','regime_held_out_delay20']))&(D.test.isin(['delay_20ms','sample_every_8','missing_30pct']))&(D.model.isin(['LR','HGB']))]
matched.groupby(['model','train','test']).average_precision.agg(['mean','std']).reset_index().to_csv(R/'fourfold_matched_frozen_mixed.csv',index=False)
# Simulator parameter and saturation audit: copied exact RNG draw order; verify old trace equality numerically.
from virtual_queue_experiment import simulator
raw=simulator(); count=0; cap=0; exceed=0; maxrho=0.; cap_rows=[]; utilrows=[]
rng=np.random.default_rng(20261009)
for ues in (1,4,10):
 for scs in (15,30):
  for capa in (1,2):
   for sinr in (5.,15.):
    for offered in (2.,5.,10.):
     for rep in range(2):
      t=0.;q_end=0.;hidden=float(np.exp(rng.normal(0,.12)))
      for i in range(150):
       phase=(i%60)/60.;sinr_now=float(sinr+rng.normal(0,2.))
       coeff=capa*(scs/15)**.32*max(.36,1+.042*(sinr_now-8))
       service_avg=1.6/coeff
       load=(ues*offered)/(40.*capa*(scs/15)**.20)
       burst=.91+.32*(np.sin(2*np.pi*phase)**2)
       util=.24+.90*load*burst*hidden*max(.65,1-.025*(sinr_now-9))
       gap=float(rng.exponential(service_avg/max(util,.03))); t+=gap
       wait=max(0.,q_end-gap);serv=float(rng.gamma(2.2,service_avg/2.2))
       noise=float(rng.exponential(.35+.06*max(0,8-sinr_now)))
       q_end=min(wait+serv,65.)
       count+=1;cap+=int(wait+serv>=65.);exceed+=int(util>1);maxrho=max(maxrho,util)
       if rep==0 and i==0:utilrows.append(dict(ues=ues,scs=scs,capa=capa,nominal_sinr=sinr,offered=offered))
assert count==len(raw)
summary={'n_packets':count,'n_scenarios':72,'n_episodes':144,'queue_workload_cap_ms':65,'frac_workload_state_clipped':cap/count,'frac_nominal_utilization_above_one':exceed/count,'max_nominal_utilization':maxrho,
 'violation_prevalence_at_thresholds_ms':{str(z):float((raw.latency_ms>z).mean()) for z in (8,12,16,20)},
 'warning':'These are diagnostics of a stylized single-server synthetic simulator, not field radio observations.'}
(R/'generator_saturation_audit.json').write_text(json.dumps(summary,indent=2))
raw.groupby('scenario_id').agg(n=('violation','size'),violation_prevalence=('violation','mean'),median_latency_ms=('latency_ms','median'),max_wait_ms=('true_wait_ms','max')).reset_index().to_csv(R/'configuration_prevalence.csv',index=False)
print('ESTIMANDS',json.dumps(comparison,indent=2));print('SATURATION',json.dumps(summary,indent=2));print('BUDGET',B.groupby(['model','budget'])[['alert_precision','capture','normalized_capture']].mean().round(4).to_string())
print('TRANSFER',pd.read_csv(R/'fourfold_matched_frozen_mixed.csv').round(4).to_string(index=False))
